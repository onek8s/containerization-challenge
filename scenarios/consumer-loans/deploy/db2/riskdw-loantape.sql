-- Group risk data warehouse (DB2 LUW 11.5, database RISKDW): consumer loan tape staging for LUCLEND.
-- Run with: db2 -td@ -vf riskdw-loantape.sql   (owned by the RISKDW team, provided for reference)

CREATE SCHEMA LOANTAPE AUTHORIZATION RISKDWADM@

CREATE TABLE LOANTAPE.CL_LOAN_TAPE_STG (
  SNAPSHOT_DATE   DATE          NOT NULL,
  SOURCE_SYSTEM   VARCHAR(10)   NOT NULL,
  ACCOUNT_NO      CHAR(12)      NOT NULL,
  CUSTOMER_NO     CHAR(10)      NOT NULL,
  PRODUCT_CODE    VARCHAR(10)   NOT NULL,
  APPLICATION_REF VARCHAR(20),
  CHANNEL         SMALLINT,
  BOOKED_TS       TIMESTAMP     NOT NULL,
  DISBURSED_TS    TIMESTAMP,
  ORIG_AMOUNT     DECIMAL(15,2) NOT NULL,
  BALANCE         DECIMAL(15,2) NOT NULL,
  ARREARS         DECIMAL(15,2) NOT NULL,
  DPD             INTEGER       NOT NULL,
  NOMINAL_RATE    DECIMAL(7,4)  NOT NULL,
  TERM_MONTHS     SMALLINT,
  RISK_GRADE      CHAR(1),
  SCORE           SMALLINT,
  IFRS9_STAGE     SMALLINT      NOT NULL,
  CORE_STATUS     CHAR(4)       NOT NULL,
  CO_BORROWER     CHAR(1)       NOT NULL DEFAULT 'N',
  LOAD_TS         TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_CL_LOAN_TAPE_STG PRIMARY KEY (SNAPSHOT_DATE, SOURCE_SYSTEM, ACCOUNT_NO)
) ORGANIZE BY ROW@

CREATE TABLE LOANTAPE.CL_LOAN_TAPE (
  SNAPSHOT_DATE   DATE          NOT NULL,
  SOURCE_SYSTEM   VARCHAR(10)   NOT NULL,
  ACCOUNT_NO      CHAR(12)      NOT NULL,
  CUSTOMER_NO     CHAR(10)      NOT NULL,
  PRODUCT_CODE    VARCHAR(10)   NOT NULL,
  APPLICATION_REF VARCHAR(20),
  ORIG_AMOUNT     DECIMAL(15,2) NOT NULL,
  BALANCE         DECIMAL(15,2) NOT NULL,
  ARREARS         DECIMAL(15,2) NOT NULL,
  DPD             INTEGER       NOT NULL,
  NOMINAL_RATE    DECIMAL(7,4)  NOT NULL,
  RISK_GRADE      CHAR(1),
  SCORE           SMALLINT,
  IFRS9_STAGE     SMALLINT      NOT NULL,
  CORE_STATUS     CHAR(4)       NOT NULL,
  CO_BORROWER     CHAR(1)       NOT NULL,
  PUBLISHED_TS    TIMESTAMP     NOT NULL,
  CONSTRAINT PK_CL_LOAN_TAPE PRIMARY KEY (SNAPSHOT_DATE, SOURCE_SYSTEM, ACCOUNT_NO)
) ORGANIZE BY COLUMN@

CREATE TABLE LOANTAPE.CL_SNAPSHOT_LOG (
  SNAPSHOT_DATE DATE        NOT NULL,
  SOURCE_SYSTEM VARCHAR(10) NOT NULL,
  ROW_COUNT     INTEGER     NOT NULL,
  TOTAL_BALANCE DECIMAL(17,2) NOT NULL,
  PUBLISHED_TS  TIMESTAMP   NOT NULL,
  PUBLISHED_BY  VARCHAR(30) NOT NULL,
  CONSTRAINT PK_CL_SNAPSHOT_LOG PRIMARY KEY (SNAPSHOT_DATE, SOURCE_SYSTEM, PUBLISHED_TS)
)@

-- Moves a complete staged snapshot into the reporting table (replaces an earlier run of the same day)
CREATE OR REPLACE PROCEDURE LOANTAPE.SP_PUBLISH_CL_SNAPSHOT (IN P_DATE DATE, IN P_SOURCE VARCHAR(10))
  LANGUAGE SQL
  MODIFIES SQL DATA
BEGIN
  DECLARE V_ROWS INTEGER DEFAULT 0;
  DECLARE V_BAL DECIMAL(17,2) DEFAULT 0;

  SELECT COUNT(*), COALESCE(SUM(BALANCE), 0) INTO V_ROWS, V_BAL
    FROM LOANTAPE.CL_LOAN_TAPE_STG WHERE SNAPSHOT_DATE = P_DATE AND SOURCE_SYSTEM = P_SOURCE;
  IF V_ROWS = 0 THEN
    SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Snapshot is empty';
  END IF;

  DELETE FROM LOANTAPE.CL_LOAN_TAPE WHERE SNAPSHOT_DATE = P_DATE AND SOURCE_SYSTEM = P_SOURCE;
  INSERT INTO LOANTAPE.CL_LOAN_TAPE
    SELECT SNAPSHOT_DATE, SOURCE_SYSTEM, ACCOUNT_NO, CUSTOMER_NO, PRODUCT_CODE, APPLICATION_REF, ORIG_AMOUNT, BALANCE, ARREARS,
           DPD, NOMINAL_RATE, RISK_GRADE, SCORE, IFRS9_STAGE, CORE_STATUS, CO_BORROWER, CURRENT TIMESTAMP
      FROM LOANTAPE.CL_LOAN_TAPE_STG WHERE SNAPSHOT_DATE = P_DATE AND SOURCE_SYSTEM = P_SOURCE;
  INSERT INTO LOANTAPE.CL_SNAPSHOT_LOG VALUES (P_DATE, P_SOURCE, V_ROWS, V_BAL, CURRENT TIMESTAMP, SESSION_USER);
END@

GRANT SELECT, INSERT, DELETE ON LOANTAPE.CL_LOAN_TAPE_STG TO USER LND_TAPE@
GRANT EXECUTE ON PROCEDURE LOANTAPE.SP_PUBLISH_CL_SNAPSHOT TO USER LND_TAPE@
