-- RATLIB/REFRATE: reference rates maintained by Treasury (daily Euribor fixings)
CREATE TABLE RATLIB.REFRATE (
  RRCODE CHAR(3)       NOT NULL,         -- E3M, E12, FIX
  RRVLDT DATE          NOT NULL,         -- valid from
  RRRATE DECIMAL(7, 4) NOT NULL,         -- percent
  RRSRCE CHAR(10)      NOT NULL DEFAULT 'EMMI',
  RRCHGT TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  PRIMARY KEY (RRCODE, RRVLDT)
) RCDFMT REFRATR;

LABEL ON TABLE RATLIB.REFRATE IS 'Reference interest rates';
GRANT SELECT ON RATLIB.REFRATE TO LNWEB, LNCOLL;
