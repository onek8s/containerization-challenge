-- Stored procedures called by the lending applications through the IBM i Access ODBC driver.
-- Result set columns match IbmICustomerService.MapLoan / GetExposureAsync.

CREATE OR REPLACE VIEW LNLIB.LN_LOAN_V AS
  SELECT LMACCT AS ACCOUNT, LMPROD AS PRODUCT, LMORIG AS ORIGINAL, LMBALA AS BALANCE, LMRATE AS RATE,
         CASE WHEN LMNXDT > 0 THEN DATE(TIMESTAMP_FORMAT(DIGITS(LMNXDT), 'YYYYMMDD')) END AS NEXT_DUE,
         LMNXAM AS NEXT_AMOUNT, LMARRS AS ARREARS, INTEGER(LMDPD) AS DPD, LMSTAT AS STATUS, LMCIF AS CIF,
         LMCOCF AS COCIF
    FROM LNLIB.LNMSTP;

CREATE OR REPLACE PROCEDURE LNLIB.LN_CUSTOMER_LOANS (IN P_CIF CHAR(10))
  LANGUAGE SQL
  READS SQL DATA
  DYNAMIC RESULT SETS 1
  SPECIFIC LNCUSLNS
  SET OPTION COMMIT = *NONE, DATFMT = *ISO
BEGIN
  DECLARE C1 CURSOR WITH RETURN TO CLIENT FOR
    SELECT ACCOUNT, PRODUCT, ORIGINAL, BALANCE, RATE, NEXT_DUE, NEXT_AMOUNT, ARREARS, DPD, STATUS, CIF
      FROM LNLIB.LN_LOAN_V
     WHERE (CIF = P_CIF OR COCIF = P_CIF) AND STATUS <> 'CLSD'
     ORDER BY ACCOUNT;
  OPEN C1;
END;

CREATE OR REPLACE PROCEDURE LNLIB.LN_LOAN_STATUS (IN P_ACCOUNT CHAR(12))
  LANGUAGE SQL
  READS SQL DATA
  DYNAMIC RESULT SETS 1
  SPECIFIC LNLNSTS
  SET OPTION COMMIT = *NONE, DATFMT = *ISO
BEGIN
  DECLARE C1 CURSOR WITH RETURN TO CLIENT FOR
    SELECT ACCOUNT, PRODUCT, ORIGINAL, BALANCE, RATE, NEXT_DUE, NEXT_AMOUNT, ARREARS, DPD, STATUS, CIF
      FROM LNLIB.LN_LOAN_V
     WHERE ACCOUNT = P_ACCOUNT;
  OPEN C1;
END;

-- Total exposure of a customer over consumer loans and overdraft limits (DPLIB)
CREATE OR REPLACE PROCEDURE LNLIB.LN_EXPOSURE_SUMMARY (IN P_CIF CHAR(10))
  LANGUAGE SQL
  READS SQL DATA
  DYNAMIC RESULT SETS 1
  SPECIFIC LNEXPSUM
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE C1 CURSOR WITH RETURN TO CLIENT FOR
    SELECT COALESCE((SELECT SUM(A.ACLIMT) FROM CIFLIB.ACCREL R JOIN DPLIB.ACMAST A ON A.ACACCT = R.ARACCT
                      WHERE R.ARCIF = P_CIF AND A.ACSTAT = 'A'), 0) + COALESCE(SUM(L.ORIGINAL), 0) AS TOTAL_LIMIT,
           COALESCE(SUM(L.BALANCE), 0) AS TOTAL_BALANCE,
           COALESCE(SUM(L.ARREARS), 0) AS TOTAL_ARREARS,
           COALESCE(MAX(L.DPD), 0) AS MAX_DPD,
           COUNT(L.ACCOUNT) AS ACTIVE_LOANS,
           COALESCE(SUM(L.NEXT_AMOUNT), 0) AS MONTHLY
      FROM LNLIB.LN_LOAN_V L
     WHERE (L.CIF = P_CIF OR L.COCIF = P_CIF) AND L.STATUS IN ('ACTV', 'COLL', 'TERM');
  OPEN C1;
END;

GRANT EXECUTE ON SPECIFIC PROCEDURE LNLIB.LNCUSLNS, LNLIB.LNLNSTS, LNLIB.LNEXPSUM TO LNWEB, LNCOLL;
