-- Core banking simulator (development and training). Mirrors the parts of CIFLIB/LNLIB/DPLIB the lending
-- platform uses; see legacy/core for the real file layouts.
CREATE TABLE IF NOT EXISTS customer (
    cif TEXT PRIMARY KEY, hetu TEXT NOT NULL UNIQUE, name TEXT NOT NULL, street TEXT NOT NULL, postal TEXT NOT NULL,
    city TEXT NOT NULL, segment TEXT NOT NULL, kyc TEXT NOT NULL, since TEXT NOT NULL, rating TEXT NOT NULL,
    deceased INTEGER NOT NULL DEFAULT 0, blocked INTEGER NOT NULL DEFAULT 0, branch TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS account (
    acct TEXT PRIMARY KEY, iban TEXT NOT NULL, cif TEXT NOT NULL, product TEXT NOT NULL, type TEXT NOT NULL,
    balance NUMERIC NOT NULL, role TEXT NOT NULL, opened TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS loan (
    acct TEXT PRIMARY KEY, cif TEXT NOT NULL, cocif TEXT, appref TEXT, product TEXT NOT NULL, original NUMERIC NOT NULL,
    balance NUMERIC NOT NULL, rate NUMERIC NOT NULL, margin NUMERIC NOT NULL, refrate TEXT NOT NULL, monthly_fee NUMERIC NOT NULL,
    instalment NUMERIC NOT NULL, due_day INTEGER NOT NULL, next_due TEXT, arrears NUMERIC NOT NULL DEFAULT 0,
    oldest_unpaid TEXT, dpd INTEGER NOT NULL DEFAULT 0, status TEXT NOT NULL, opened TEXT NOT NULL, term INTEGER NOT NULL,
    disbursed INTEGER NOT NULL DEFAULT 0, plan INTEGER NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS ix_loan_appref ON loan(appref) WHERE appref IS NOT NULL;
CREATE TABLE IF NOT EXISTS txn (
    id INTEGER PRIMARY KEY AUTOINCREMENT, acct TEXT NOT NULL, date TEXT NOT NULL, type TEXT NOT NULL, amount NUMERIC NOT NULL,
    principal NUMERIC NOT NULL, interest NUMERIC NOT NULL, fees NUMERIC NOT NULL, balance_after NUMERIC NOT NULL);
CREATE TABLE IF NOT EXISTS evt (
    id INTEGER PRIMARY KEY AUTOINCREMENT, type TEXT NOT NULL, acct TEXT NOT NULL, ts TEXT NOT NULL, amount NUMERIC NOT NULL,
    arrears NUMERIC NOT NULL, dpd INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS plan (acct TEXT NOT NULL, n INTEGER NOT NULL, due TEXT NOT NULL, amount NUMERIC NOT NULL, PRIMARY KEY (acct, n));
CREATE TABLE IF NOT EXISTS refrate (code TEXT NOT NULL, valid TEXT NOT NULL, rate NUMERIC NOT NULL, PRIMARY KEY (code, valid));
CREATE TABLE IF NOT EXISTS busdate (id INTEGER PRIMARY KEY CHECK (id = 1), date TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS seq (name TEXT PRIMARY KEY, value INTEGER NOT NULL);
