-- Business days around today: index 0 is today (or the next weekday), negative indexes are in the past.
IF OBJECT_ID('tempdb..#bd') IS NOT NULL DROP TABLE #bd;
CREATE TABLE #bd (Idx int PRIMARY KEY, D date NOT NULL);
DECLARE @day date = CAST(GETDATE() AS date), @i int = 0;
WHILE DATEPART(weekday, @day) IN (1, 7) SET @day = DATEADD(day, 1, @day); -- assumes DATEFIRST 7 (us_english)
INSERT #bd VALUES (0, @day);
DECLARE @f date = @day, @b date = @day;
SET @i = 1;
WHILE @i <= 20
BEGIN
    SET @f = DATEADD(day, 1, @f); WHILE DATEPART(weekday, @f) IN (1, 7) SET @f = DATEADD(day, 1, @f);
    SET @b = DATEADD(day, -1, @b); WHILE DATEPART(weekday, @b) IN (1, 7) SET @b = DATEADD(day, -1, @b);
    INSERT #bd VALUES (@i, @f), (-@i, @b);
    SET @i = @i + 1;
END

