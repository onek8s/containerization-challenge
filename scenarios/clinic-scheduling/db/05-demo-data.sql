    EXEC dbo.usp_LabOrder_Create @EncounterId = @enc, @PatientId = @pat, @ProviderId = @prov, @TestCode = 'CMP', @LabOrderId = @oid OUTPUT, @OrderNumber = @onum OUTPUT;
    UPDATE dbo.LabOrder SET SentOn = DATEADD(hour, 10, CAST(@dos AS datetime)), OrderedOn = DATEADD(hour, 9, CAST(@dos AS datetime)) WHERE LabOrderId = @oid;
